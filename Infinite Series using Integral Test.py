import numpy as np
import scipy.integrate as integrate

# 1. Define sequence term f(n) and continuous function f(x)
def a_n(n):
    return 1.0 / (n**2)

def f_x(x):
    return 1.0 / (x**2)

# 2. Core Numerical Algorithm for Integral Test Approximation
def integral_test_approximation(N_terms):
    # Compute Partial Sum S_N
    n_values = np.arange(1, N_terms + 1)
    s_n = np.sum(a_n(n_values))

    # Compute Improper Integrals for Tail Bounds using SciPy quad
    lower_integral, _ = integrate.quad(f_x, N_terms + 1, np.inf)
    upper_integral, _ = integrate.quad(f_x, N_terms, np.inf)

    # Calculate Total Sum Bounds, Best Midpoint Estimate, and Error Bound
    min_sum = s_n + lower_integral
    max_sum = s_n + upper_integral
    best_estimate = (min_sum + max_sum) / 2.0
    error_bound = upper_integral - lower_integral

    return s_n, min_sum, max_sum, best_estimate, error_bound

# Execution example with N = 10 terms
N = 10
s_n, low, high, best_est, err = integral_test_approximation(N)

print(f"Partial Sum (S_N): {s_n:.6f}")
print(f"Lower Bound:       {low:.6f}")
print(f"Upper Bound:       {high:.6f}")
print(f"Best Estimate:     {best_est:.6f}")
print(f"Max Error Bound:   {err:.6f}")